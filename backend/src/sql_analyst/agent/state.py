"""Agent state (BUILD_GUIDE §8.1). LangGraph passes it between nodes.

Nodes return partial updates. `sql_attempts`, `trace`, and `llm_calls` are append-only
(each update adds to the list); every other field is replaced by the value a node returns.
"""

import operator
from decimal import Decimal
from typing import Annotated, Any, Literal

from pydantic import BaseModel, Field, PlainSerializer

from sql_analyst.agent.guard import RefusalKind
from sql_analyst.agent.schemas import ChartSpec
from sql_analyst.observability import LLMCall, NodeEvent
from sql_analyst.safety.scope import UserScope

Status = Literal["running", "answered", "refused", "partial", "error"]


class ViewHit(BaseModel):
    name: str
    score: float


class ValueMatch(BaseModel):
    """A phrase in the question that matches a real value of a categorical column."""

    phrase: str
    view: str
    column: str
    value: str
    score: float


class ExampleHit(BaseModel):
    id: str
    question: str
    decision: str
    sql: str | None = None
    score: float


class RetrievedContext(BaseModel):
    """What retrieval found for this question, ranked. Rendered into the SQL prompt."""

    views: list[ViewHit] = Field(default_factory=list)
    metrics: list[str] = Field(default_factory=list)
    values: list[ValueMatch] = Field(default_factory=list)
    examples: list[ExampleHit] = Field(default_factory=list)
    full_schema: bool = False  # the no-retrieval ablation: the whole dictionary is in the prompt


class SQLAttempt(BaseModel):
    """One pass through generate -> validate -> execute -> check, and why it failed (if it did)."""

    sql: str | None
    stage: Literal["generate", "validate", "execute", "check"]
    ok: bool
    error_code: str | None = None
    error: str | None = None


def _json_cell(value: Any) -> Any:
    """Postgres numerics arrive as Decimal, which pydantic writes to JSON as a string.
    Write a number instead, as the stream does, so stored runs chart and format alike."""
    if isinstance(value, Decimal):
        if value.is_finite() and value == value.to_integral_value():
            return int(value)
        return float(value)
    return value


# A result cell. Every model that carries result rows uses it, so JSON always gets numbers.
Cell = Annotated[Any, PlainSerializer(_json_cell, when_used="json")]


class ResultTable(BaseModel):
    columns: list[str]
    rows: list[list[Cell]]
    row_count: int
    truncated: bool
    plan_cost: float = 0.0
    elapsed_ms: float = 0.0


class Refusal(BaseModel):
    kind: RefusalKind
    reason: str
    source: Literal["guard", "model"]


class AgentState(BaseModel):
    run_id: str = ""
    question: str
    user: UserScope
    session_id: str | None = None  # a demo sign-in's browser session (API); scopes its history
    lang: Literal["en", "id"] = "en"
    started: float = 0.0  # time.perf_counter() at the start of the run
    goto: str | None = None  # set by a node to leave the default path (repair, refuse, finalize)

    context: RetrievedContext | None = None
    draft_sql: str | None = None  # the latest generated SQL
    validated_sql: str | None = None  # regenerated by the validator; what the database runs
    sql: str | None = None  # the SQL behind the result shown to the user
    sql_attempts: Annotated[list[SQLAttempt], operator.add] = Field(default_factory=list)
    feedback: str | None = None  # the error the next generate_sql turn must fix
    repairs: int = 0  # times a failed attempt sent the run back to generate_sql
    result_checks: int = 0  # times check_result sent the run back
    assumptions: list[str] = Field(default_factory=list)
    confidence: str | None = None

    result: ResultTable | None = None
    answer_template: str | None = None
    answer_feedback: str | None = None  # why render_numbers rejected the last template
    answer_attempts: int = 0
    answer: str | None = None
    answer_fallback: bool = False  # table-only answer written by code
    caveats: list[str] = Field(default_factory=list)  # written by code
    model_caveats: list[str] = Field(default_factory=list)  # written by the model (digit-checked)
    chart: ChartSpec | None = None

    status: Status = "running"
    refusal: Refusal | None = None
    suggestions: list[str] = Field(default_factory=list)  # follow-ups offered with a refusal
    error: str | None = None
    stop_reason: str | None = None  # which budget limit stopped the run

    trace: Annotated[list[NodeEvent], operator.add] = Field(default_factory=list)
    llm_calls: Annotated[list[LLMCall], operator.add] = Field(default_factory=list)
    response: Any = None  # the AgentResult built by finalize
